/**
 * Parsea rigurosamente fechas en formato 'YYYY-MM-DD' o 'DD/MM/YYYY' a objetos Date válidos de JavaScript
 * Asigna las 12:00:00 para neutralizar cualquier desvío por huso horario o horario de verano.
 */
export function parseDateStrict(dateStr: string): Date {
  if (!dateStr) return new Date(2024, 8, 23, 12, 0, 0);

  const clean = String(dateStr).trim();

  // YYYY-MM-DD
  const isoParts = clean.split('-');
  if (isoParts.length === 3) {
    const y = parseInt(isoParts[0], 10);
    const m = parseInt(isoParts[1], 10) - 1; // 0-indexed in JS (8 = Septiembre)
    const d = parseInt(isoParts[2], 10);
    if (!isNaN(y) && !isNaN(m) && !isNaN(d)) {
      return new Date(y, m, d, 12, 0, 0);
    }
  }

  // DD/MM/YYYY
  const slashParts = clean.split('/');
  if (slashParts.length === 3) {
    const d = parseInt(slashParts[0], 10);
    const m = parseInt(slashParts[1], 10) - 1;
    const y = parseInt(slashParts[2], 10);
    if (!isNaN(y) && !isNaN(m) && !isNaN(d)) {
      return new Date(y, m, d, 12, 0, 0);
    }
  }

  const fallback = new Date(clean);
  return isNaN(fallback.getTime()) ? new Date(2024, 8, 23, 12, 0, 0) : fallback;
}

